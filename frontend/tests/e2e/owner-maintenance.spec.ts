test('CT7 failed refresh removes private details and a retry fetches the real record again', async ({ page }) => {
  await login(page); await page.goto('/owner/maintenance/1')
  await expect(page.getByRole('heading', { name: 'Vòi nước phòng A101 bị rò', exact: true })).toBeVisible()
  await page.route('**/api/owner/maintenance-requests/1', route => route.abort('failed'))
  await page.getByRole('button', { name: 'Tải lại yêu cầu', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Chưa thể tải thông tin', exact: true })).toBeVisible()
  await expect(page.getByText('Nước rỉ ở van dưới bồn rửa.', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Cập nhật xử lý', exact: true })).toHaveCount(0)
  await page.unroute('**/api/owner/maintenance-requests/1')
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.getByText('Nước rỉ ở van dưới bồn rửa.', { exact: true })).toBeVisible()
})
