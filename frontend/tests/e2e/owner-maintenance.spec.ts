  await dialog.getByLabel('Kết quả sửa chữa (bắt buộc)', { exact: true }).fill('Đã sửa xong và kiểm tra an toàn.')
  await dialog.getByRole('button', { name: 'Xem lại cập nhật', exact: true }).click()
  // Another owner tab really changes the row after this form captured its token.
  const before = (await (await page.request.get('/api/owner/maintenance-requests/2')).json()).data
  expect((await processRequest(page, { version_token: before.version_token, status: 'in_progress', resolution: 'Phiên khác đã đặt lịch kiểm tra ngày mai.' })).status()).toBe(200)
  await dialog.getByRole('button', { name: 'Xác nhận cập nhật', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Tải bản mới nhất', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Xác nhận cập nhật', exact: true })).toHaveCount(0)
  expect((await (await page.request.get('/api/owner/maintenance-requests/2')).json()).data.resolution).toBe('Phiên khác đã đặt lịch kiểm tra ngày mai.')
  await dialog.getByRole('button', { name: 'Tải bản mới nhất', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Phiên khác đã đặt lịch kiểm tra ngày mai.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cập nhật xử lý', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Trạng thái xử lý (bắt buộc)', { exact: true }).selectOption('resolved')
  await dialog.getByLabel('Kết quả sửa chữa (bắt buộc)', { exact: true }).fill('Đã sửa xong và kiểm tra an toàn.')
  await dialog.getByRole('button', { name: 'Xem lại cập nhật', exact: true }).click()
  await expect(dialog.getByText('Sau khi hoàn tất, kết quả sẽ được giữ lại và không thể sửa tiếp.', { exact: true })).toBeVisible()
