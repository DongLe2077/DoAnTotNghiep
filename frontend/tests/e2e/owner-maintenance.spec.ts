  await expect(dialog.getByRole('alert').first()).toContainText('Phiên bảo mật đã thay đổi')
  expect(attempts).toBe(1)
  expect((await (await page.request.get('/api/owner/maintenance-requests/2')).json()).data.status).toBe('submitted')
  await dialog.getByRole('button', { name: 'Xác nhận cập nhật', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(attempts).toBe(2)
  await expect(page.getByText('Đã tiếp nhận, hẹn thợ kiểm tra chiều nay.', { exact: true })).toBeVisible()

