async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('e2e_owner')
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).toHaveURL('/owner')
}
async function mutation(page: Page, method: string, path: string, data?: unknown) {
  await page.request.get('/api/auth/csrf-cookie')
  const token = (await page.context().cookies()).find(item => item.name === 'XSRF-TOKEN')!
  const result = await page.request.fetch(`/api/owner${path}`, { method, data, headers: { 'X-XSRF-TOKEN': decodeURIComponent(token.value) } })
  expect(result.ok(), await result.text()).toBe(true)
  return result.status() === 204 ? null : (await result.json()).data
}
async function picker(page: Page, label: string, text: string) {
  const field = page.getByRole('group', { name: label, exact: true })
  await field.getByRole('radio').filter({ visible: true }).count()
  await field.getByLabel(`Tìm ${label.toLocaleLowerCase('vi-VN')}`, { exact: true }).fill(text)
  await field.getByRole('button', { name: 'Tìm', exact: true }).click()
  await field.getByText(text, { exact: false }).last().click()
}
async function action(page: Page, title: string, time: string, select?: { label: string; name: string }) {
  await page.getByRole('button', { name: title, exact: true }).click()
  if (select) await picker(page, select.label, select.name)
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Thời điểm thực hiện (giờ Việt Nam) (bắt buộc)', { exact: true }).fill(time.replace(/:00$/, ''))
  await dialog.getByRole('button', { name: 'Xem lại thao tác', exact: true }).click()
  const reviewTitle = title === 'Chọn / đổi đại diện' ? 'Đổi người đại diện' : title.startsWith('Ghi rời phòng:') ? 'Thành viên rời phòng' : title.startsWith('Ngừng ') ? 'Ngừng dịch vụ' : title
  await expect(dialog.getByRole('heading', { name: `Xem lại: ${reviewTitle}` })).toBeVisible()
  await dialog.getByRole('button', { name: 'Xác nhận thực hiện', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('heading', { name: /^Đợt thuê phòng / })).toBeVisible()
}
async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true) }

