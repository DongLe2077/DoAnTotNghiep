test('owner create forms never resend a CSRF-rejected write and offer explicit retry', async ({ page }) => {
  await login(page); await page.goto('/owner/tenants')
  await page.getByRole('button', { name: 'Thêm người thuê', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Họ và tên (bắt buộc)').fill('Người thuê thử lại')
  await dialog.getByLabel('Số điện thoại (bắt buộc)').fill('0900999000')
  let attempts = 0
  await page.route('**/api/owner/tenants', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    attempts++
    if (attempts === 1) await route.fulfill({ status: 419, contentType: 'application/json', body: JSON.stringify({ message: 'Phiên bảo mật đã thay đổi. Vui lòng thử lại thao tác.' }) })
    else await route.continue()
  })
  await dialog.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click()
  await expect(dialog.getByRole('alert').first()).toContainText('Phiên bảo mật đã thay đổi')
  expect(attempts).toBe(1)
  await expect(dialog.getByLabel('Họ và tên (bắt buộc)')).toHaveValue('Người thuê thử lại')
  await dialog.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click()
  await expect(page).toHaveURL(/\/owner\/tenants\/\d+$/)
  expect(attempts).toBe(2)
})

